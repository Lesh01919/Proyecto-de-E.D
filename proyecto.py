import numpy as np
import matplotlib.pyplot as plt

# 1. MÉTODO DE HEUN (EULER MEJORADO)

def heun(f, t0, tf, y0, h):
    y0 = np.array(y0, dtype=float)

    n = int(round((tf - t0) / h))
    t = np.linspace(t0, tf, n + 1)

    Y = np.zeros((n + 1, len(y0)))
    Y[0] = y0

    for i in range(n):
        dt = t[i+1] - t[i]

        # Primera pendiente
        k1 = f(t[i], Y[i])

        # Predicción con Euler
        y_pred = Y[i] + dt * k1

        # Segunda pendiente
        k2 = f(t[i+1], y_pred)

        # Corrección de Heun
        Y[i+1] = Y[i] + (dt/2)*(k1+k2)

    return t, Y


# 2. SISTEMA MASA-RESORTE-AMORTIGUADOR
# Ecuación:
# m*x'' + b*x' + k*x = 0

m = 1.0
b = 2.0
k = 5.0

def masa_resorte(t, y):
    x, v = y

    dx = v
    dv = -(b/m)*v - (k/m)*x

    return np.array([dx, dv])


# Condiciones iniciales
# x(0) = 1, v(0) = 0

t, Y = heun(
    masa_resorte,
    0,
    10,
    [1, 0],
    0.05
)

# Solución analítica
x_exacta = np.exp(-t) * (
    np.cos(2*t) + 0.5*np.sin(2*t)
)

# Error
error_mecanico = np.abs(Y[:, 0] - x_exacta)

# Gráfica
plt.figure(figsize=(9, 5))

plt.plot(t, x_exacta, label="Solución analítica")
plt.plot(t, Y[:, 0], "--", label="Método de Heun")

plt.title("Sistema masa-resorte-amortiguador")
plt.xlabel("Tiempo (s)")
plt.ylabel("Posición (m)")
plt.legend()
plt.grid(True)
plt.show()

print("ERROR MÁXIMO - MASA RESORTE:")
print(np.max(error_mecanico))


# 3. CIRCUITO RLC
# Ecuación:
# L*q'' + R*q' + q/C = 0

L = 1.0
R = 2.0
C = 0.2

def circuito_rlc(t, y):
    q, corriente = y

    dq = corriente
    di = -(R/L)*corriente - q/(L*C)

    return np.array([dq, di])


# Condiciones iniciales
# q(0) = 1, i(0) = 0

t, Y = heun(
    circuito_rlc,
    0,
    10,
    [1, 0],
    0.05
)

# Solución analítica
q_exacta = np.exp(-t) * (
    np.cos(2*t) + 0.5*np.sin(2*t)
)

# Error
error_rlc = np.abs(Y[:, 0] - q_exacta)

# Gráfica
plt.figure(figsize=(9, 5))

plt.plot(t, q_exacta, label="Solución analítica")
plt.plot(t, Y[:, 0], "--", label="Método de Heun")

plt.title("Circuito RLC")
plt.xlabel("Tiempo (s)")
plt.ylabel("Carga eléctrica (C)")
plt.legend()
plt.grid(True)
plt.show()

print("ERROR MÁXIMO - CIRCUITO RLC:")
print(np.max(error_rlc))