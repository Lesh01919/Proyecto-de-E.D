import numpy as np
import matplotlib.pyplot as plt


# 1. MÉTODO RUNGE-KUTTA DE CUARTO ORDEN

def rk4(f, t0, tf, y0, h):

    y0 = np.array(y0, dtype=float)

    n = int(round((tf - t0) / h))

    t = np.linspace(t0, tf, n + 1)

    Y = np.zeros((n + 1, len(y0)))

    Y[0] = y0

    for i in range(n):

        hi = t[i + 1] - t[i]

        k1 = f(t[i], Y[i])

        k2 = f(
            t[i] + hi/2,
            Y[i] + hi*k1/2
        )

        k3 = f(
            t[i] + hi/2,
            Y[i] + hi*k2/2
        )

        k4 = f(
            t[i] + hi,
            Y[i] + hi*k3
        )

        Y[i+1] = Y[i] + (hi/6) * (
            k1 + 2*k2 + 2*k3 + k4
        )

    return t, Y


# 2. SISTEMA MECÁNICO

def sistema_mecanico(t, y):

    x1, x2 = y

    return np.array([
        x2,
        -4*x1 - 2*x2
    ])


def solucion_mecanica(t):

    return np.exp(-t) * (
        np.cos(np.sqrt(3)*t)
        + np.sin(np.sqrt(3)*t)/np.sqrt(3)
    )


t, Y = rk4(
    sistema_mecanico,
    0,
    10,
    [1, 0],
    0.05
)

exacta = solucion_mecanica(t)

plt.figure(figsize=(9, 5))

plt.plot(t, exacta, label="Solución analítica")

plt.plot(
    t,
    Y[:, 0],
    "--",
    label="RK4"
)

plt.title("Sistema mecánico")
plt.xlabel("Tiempo")
plt.ylabel("x1(t)")
plt.legend()
plt.grid(True)
plt.show()


# 3. SISTEMA ELÉCTRICO

def sistema_electrico(t, y):

    x1, x2 = y

    return np.array([
        -2*x1 - x2,
        x1
    ])


def solucion_electrica(t):

    return (1 + t) * np.exp(-t)


t, Y = rk4(
    sistema_electrico,
    0,
    10,
    [0, 1],
    0.05
)

exacta = solucion_electrica(t)

plt.figure(figsize=(9, 5))

plt.plot(
    t,
    exacta,
    label="Solución analítica"
)

plt.plot(
    t,
    Y[:, 1],
    "--",
    label="RK4"
)

plt.title("Sistema eléctrico")
plt.xlabel("Tiempo")
plt.ylabel("x2(t)")
plt.legend()
plt.grid(True)
plt.show()


# 4. OSCILADOR DE VAN DER POL

def van_der_pol(t, y):

    mu = 1

    x1, x2 = y

    return np.array([
        x2,
        mu*(1-x1**2)*x2 - x1
    ])


pasos = [0.2, 0.1, 0.05, 0.025]

plt.figure(figsize=(10, 5))

for h in pasos:

    t, Y = rk4(
        van_der_pol,
        0,
        20,
        [2, 0],
        h
    )

    plt.plot(
        t,
        Y[:, 0],
        label=f"h = {h}"
    )

plt.title("Oscilador de Van der Pol")
plt.xlabel("Tiempo")
plt.ylabel("x1(t)")
plt.legend()
plt.grid(True)
plt.show()


# 5. ANÁLISIS DE CONVERGENCIA

